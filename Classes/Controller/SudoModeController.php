declare(strict_types=1);

namespace Netresearch\NrPasskeysBe\Controller;

use Netresearch\NrPasskeysBe\Service\CredentialRepository;
use Netresearch\NrPasskeysBe\Service\RateLimiterService;
use Netresearch\NrPasskeysBe\Service\SudoModeTokenService;
use Netresearch\NrPasskeysBe\Service\WebAuthnService;
use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\ServerRequestInterface;
use Psr\Log\LoggerInterface;
use RuntimeException;
use Throwable;
use TYPO3\CMS\Core\Authentication\BackendUserAuthentication;
use TYPO3\CMS\Core\Http\JsonResponse;

use function base64_decode;
use function is_array;
use function is_string;
use function json_decode;
use function json_encode;
use function ord;
use function preg_match;
use function strlen;
use function strtr;

/**
 * Confirms a TYPO3 sudo-mode claim with a passkey instead of the password.
 *
 * Two steps, both for the user who is already logged in:
 *
 * 1. options: assertion options limited to that user's own credentials, with
 *    the configured user verification (PIN, biometrics).
 * 2. verify:  the assertion is checked exactly like a login assertion. On
 *    success the browser gets a token (SudoModeTokenService) that it submits
 *    through the core's own sudo-mode form; VerifySudoModeWithPasskey accepts
 *    it there. Nothing here grants access by itself.
 */
final class SudoModeController
{
    use BackendUserTrait;
    use JsonBodyTrait;

    /** Claim ids are generated by the core; anything else is not one. */
    private const CLAIM_ID_PATTERN = '/^[A-Za-z0-9_.-]{1,128}$/';

    public function __construct(
        private readonly WebAuthnService $webAuthnService,
        private readonly CredentialRepository $credentialRepository,
        private readonly RateLimiterService $rateLimiterService,
        private readonly SudoModeTokenService $tokenService,
        private readonly LoggerInterface $logger,
    ) {}

    /**
     * POST /passkeys/sudo-mode/options.
     *
     * Answers {"available": false} when the user has no passkey, so the
     * browser shows the password form only.
     */
    public function optionsAction(ServerRequestInterface $request): ResponseInterface
    {
        $user = $this->getAuthenticatedUser();

        if ($user === null || $this->getSessionIdentifier() === '') {
            return new JsonResponse(['error' => 'Not authenticated'], 401);
        }

        if ($this->credentialRepository->countByBeUser($user->uid) === 0) {
            return new JsonResponse(['available' => false]);
        }

        try {
            $this->rateLimiterService->consumeRateLimit('sudo_options', (string) $user->uid);
        } catch (RuntimeException) {
            return new JsonResponse(['error' => 'Too many attempts'], 429);
        }

        try {
            $result  = $this->webAuthnService->createAssertionOptions($user->username, $user->uid);
            $options = json_decode(
                $this->webAuthnService->serializeRequestOptions($result->options),
                true,
                512,
                JSON_THROW_ON_ERROR,
            );

            if (is_array($options)) {
                // Whatever login is configured to accept: a step-up needs the
                // person, not just the key. verifyAction checks the flag.
                $options['userVerification'] = 'required';
            }

            return new JsonResponse([
                'available'      => true,
                'options'        => $options,
                'challengeToken' => $result->challengeToken,
            ]);
        } catch (Throwable $e) {
            $this->logger->error('Failed to generate sudo mode assertion options', [
                'be_user_uid' => $user->uid,
                'error'       => $e->getMessage(),
            ]);

            return new JsonResponse(['error' => 'Failed to generate options'], 500);
        }
    }

    /**
     * POST /passkeys/sudo-mode/verify
     * Body: { "claim": "...", "challengeToken": "...", "credential": {...} }.
     */
    public function verifyAction(ServerRequestInterface $request): ResponseInterface
    {
        $user              = $this->getAuthenticatedUser();
        $sessionIdentifier = $this->getSessionIdentifier();

        if ($user === null || $sessionIdentifier === '') {
            return new JsonResponse(['error' => 'Not authenticated'], 401);
        }

        $body           = $this->getJsonBody($request);
        $claimId        = is_string($body['claim'] ?? null) ? $body['claim'] : '';
        $challengeToken = is_string($body['challengeToken'] ?? null) ? $body['challengeToken'] : '';
        $credential     = $body['credential'] ?? null;

        if (preg_match(self::CLAIM_ID_PATTERN, $claimId) !== 1 || $challengeToken === '' || !is_array($credential)) {
            return new JsonResponse(['error' => 'Missing required fields'], 400);
        }

        try {
            $this->rateLimiterService->consumeRateLimit('sudo_verify', (string) $user->uid);
        } catch (RuntimeException) {
            return new JsonResponse(['error' => 'Too many attempts'], 429);
        }

        try {
            $this->webAuthnService->verifyAssertionResponse(
                responseJson: json_encode($credential, JSON_THROW_ON_ERROR),
                challengeToken: $challengeToken,
                beUserUid: $user->uid,
            );

            // The signature covers the authenticator data, so after a
            // successful check the flags can be trusted.
            if (!self::userWasVerified($credential)) {
                throw new RuntimeException('The authenticator did not verify the user', 1795600001);
            }
        } catch (Throwable $e) {
            $this->logger->warning('Sudo mode passkey verification failed', [
                'be_user_uid' => $user->uid,
                'error'       => $e->getMessage(),
            ]);

            return new JsonResponse(['error' => 'Verification failed'], 403);
        }

        $this->logger->info('Sudo mode confirmed with passkey', [
            'be_user_uid' => $user->uid,
        ]);

        return new JsonResponse([
            'token' => $this->tokenService->issue($user->uid, $sessionIdentifier, $claimId),
        ]);
    }

    /**
     * The UV bit (0x04) of the flags byte that follows the 32-byte RP id hash
     * in the authenticator data.
     *
     * @param array<mixed> $credential
     */
    private static function userWasVerified(array $credential): bool
    {
        $response = $credential['response'] ?? null;
        $encoded  = is_array($response) ? ($response['authenticatorData'] ?? null) : null;

        if (!is_string($encoded) || $encoded === '') {
            return false;
        }

        $data = base64_decode(strtr($encoded, '-_', '+/'), true);

        if ($data === false || strlen($data) < 37) {
            return false;
        }

        return (ord($data[32]) & 0x04) === 0x04;
    }

    private function getSessionIdentifier(): string
    {
        $backendUser = $GLOBALS['BE_USER'] ?? null;

        if (!$backendUser instanceof BackendUserAuthentication) {
            return '';
        }

        return $backendUser
            ->getSession()
            ->getIdentifier();
    }
}
